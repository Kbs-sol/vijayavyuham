// ============================================================
// Generates supabase/schema.sql (Postgres schema + seed) from the
// single source of truth: src/lib/seed-data.ts
//
//   node scripts/gen-supabase-sql.mjs
//
// The output is a copy-paste script for the Supabase SQL editor.
// Run it once against a fresh Supabase project to create every table
// and load the same default content the offline store ships with.
// ============================================================
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// --- load SEED (strip the TS `export const SEED =` wrapper) ---
const tsSrc = readFileSync(join(root, 'src/lib/seed-data.ts'), 'utf8');
const start = tsSrc.indexOf('{', tsSrc.indexOf('SEED'));
const end = tsSrc.lastIndexOf('}');
const SEED = JSON.parse(tsSrc.slice(start, end + 1));

// --- helpers ---
const q = (v) => {
  if (v === null || v === undefined) return 'NULL';
  return `'${String(v).replace(/'/g, "''")}'`;
};
const num = (v) => (v === null || v === undefined || v === '' ? '0' : String(Number(v)));

const out = [];
out.push(`-- ============================================================
-- Vijayavyuham — Supabase (PostgreSQL) schema + seed
-- ------------------------------------------------------------
-- HOW TO USE
--   1. Create a Supabase project  ->  https://supabase.com
--   2. Open  SQL Editor  ->  New query
--   3. Paste this ENTIRE file and click RUN.
--   4. Copy Project URL + service_role key into Cloudflare secrets
--      (see .dev.vars.example / SYSTEM_GUIDE.md).
--
-- Safe to re-run: tables use IF NOT EXISTS; seed rows use upsert.
-- AUTO-GENERATED from src/lib/seed-data.ts — do not edit by hand.
-- ============================================================

-- ---------- TABLES ----------

create table if not exists settings (
  key         text primary key,
  value       text,
  updated_at  timestamptz default now()
);

create table if not exists services (
  id           bigint generated by default as identity primary key,
  slug         text unique not null,
  sort_order   int default 0,
  icon         text default 'fa-chart-line',
  title_en text not null, short_en text, description_en text,
  title_te text, short_te text, description_te text,
  title_hi text, short_hi text, description_hi text,
  features     text default '[]',
  image_url    text,
  is_active    int default 1,
  created_at   timestamptz default now(),
  updated_at   timestamptz default now()
);

create table if not exists blogs (
  id           bigint generated by default as identity primary key,
  slug         text unique not null,
  category     text default 'General',
  cover_image  text,
  author       text default 'Vijayavyuham Team',
  title_en text not null, excerpt_en text, content_en text,
  title_te text, excerpt_te text, content_te text,
  title_hi text, excerpt_hi text, content_hi text,
  meta_title text, meta_description text, keywords text,
  is_published int default 1,
  published_at timestamptz default now(),
  created_at   timestamptz default now(),
  updated_at   timestamptz default now()
);

-- Gallery uses media_url + media_type (universal embed: Cloudinary / YouTube / Vimeo / image / video)
create table if not exists gallery (
  id          bigint generated by default as identity primary key,
  media_url   text not null,
  media_type  text default 'auto',
  category    text default 'General',
  sort_order  int default 0,
  title_en text, title_te text, title_hi text,
  caption_en text, caption_te text, caption_hi text,
  is_active   int default 1,
  created_at  timestamptz default now()
);

create table if not exists team (
  id          bigint generated by default as identity primary key,
  name        text not null,
  photo_url   text,
  sort_order  int default 0,
  role_en text, role_te text, role_hi text,
  bio_en text, bio_te text, bio_hi text,
  linkedin text, twitter text, email text,
  is_active   int default 1,
  created_at  timestamptz default now()
);

create table if not exists testimonials (
  id          bigint generated by default as identity primary key,
  author_name text not null,
  author_role text,
  photo_url   text,
  sort_order  int default 0,
  quote_en text, quote_te text, quote_hi text,
  is_active   int default 1,
  created_at  timestamptz default now()
);

create table if not exists enquiries (
  id            bigint generated by default as identity primary key,
  name          text not null,
  email         text,
  phone         text,
  subject       text,
  message       text,
  service_interest text,
  source_page   text,
  status        text default 'new',
  is_read       int default 0,
  created_at    timestamptz default now()
);

create index if not exists idx_services_active   on services(is_active, sort_order);
create index if not exists idx_blogs_published    on blogs(is_published, published_at);
create index if not exists idx_gallery_active     on gallery(is_active, sort_order);
create index if not exists idx_team_active         on team(is_active, sort_order);
create index if not exists idx_enquiries_status    on enquiries(status, created_at);
`);

// ---------- SEED: settings ----------
out.push(`\n-- ---------- SEED: settings ----------`);
const sEntries = Object.entries(SEED.settings || {});
out.push(`insert into settings (key, value) values`);
out.push(
  sEntries.map(([k, v]) => `  (${q(k)}, ${q(v === null || v === undefined ? '' : String(v))})`).join(',\n') +
  `\non conflict (key) do update set value = excluded.value, updated_at = now();`
);

// ---------- SEED: services ----------
const svc = SEED.services || [];
if (svc.length) {
  out.push(`\n-- ---------- SEED: services ----------`);
  const cols = ['slug','sort_order','icon','title_en','short_en','description_en','title_te','short_te','description_te','title_hi','short_hi','description_hi','features','image_url','is_active'];
  out.push(`insert into services (${cols.join(', ')}) values`);
  out.push(svc.map((r) =>
    `  (${q(r.slug)}, ${num(r.sort_order)}, ${q(r.icon || 'fa-chart-line')}, ${q(r.title_en)}, ${q(r.short_en)}, ${q(r.description_en)}, ${q(r.title_te)}, ${q(r.short_te)}, ${q(r.description_te)}, ${q(r.title_hi)}, ${q(r.short_hi)}, ${q(r.description_hi)}, ${q(r.features || '[]')}, ${q(r.image_url)}, ${num(r.is_active ?? 1)})`
  ).join(',\n') + `\non conflict (slug) do nothing;`);
}

// ---------- SEED: blogs ----------
const blogs = SEED.blogs || [];
if (blogs.length) {
  out.push(`\n-- ---------- SEED: blogs ----------`);
  const cols = ['slug','category','cover_image','author','title_en','excerpt_en','content_en','title_te','excerpt_te','content_te','title_hi','excerpt_hi','content_hi','meta_title','meta_description','keywords','is_published'];
  out.push(`insert into blogs (${cols.join(', ')}) values`);
  out.push(blogs.map((r) =>
    `  (${q(r.slug)}, ${q(r.category || 'General')}, ${q(r.cover_image)}, ${q(r.author || 'Vijayavyuham Team')}, ${q(r.title_en)}, ${q(r.excerpt_en)}, ${q(r.content_en)}, ${q(r.title_te)}, ${q(r.excerpt_te)}, ${q(r.content_te)}, ${q(r.title_hi)}, ${q(r.excerpt_hi)}, ${q(r.content_hi)}, ${q(r.meta_title)}, ${q(r.meta_description)}, ${q(r.keywords)}, ${num(r.is_published ?? 1)})`
  ).join(',\n') + `\non conflict (slug) do nothing;`);
}

// ---------- SEED: testimonials ----------
const tst = SEED.testimonials || [];
if (tst.length) {
  out.push(`\n-- ---------- SEED: testimonials ----------`);
  const cols = ['author_name','author_role','photo_url','sort_order','quote_en','quote_te','quote_hi','is_active'];
  out.push(`insert into testimonials (${cols.join(', ')}) values`);
  out.push(tst.map((r) =>
    `  (${q(r.author_name)}, ${q(r.author_role)}, ${q(r.photo_url)}, ${num(r.sort_order)}, ${q(r.quote_en)}, ${q(r.quote_te)}, ${q(r.quote_hi)}, ${num(r.is_active ?? 1)})`
  ).join(',\n') + `\non conflict do nothing;`);
}

out.push(`\n-- Done. Your Supabase database is ready.\n`);

mkdirSync(join(root, 'supabase'), { recursive: true });
writeFileSync(join(root, 'supabase/schema.sql'), out.join('\n'));
console.log('Wrote supabase/schema.sql');
